"""Fallback generator: creates Cisco IOS CLI configuration scripts, address tables, and manual guides."""

from __future__ import annotations

import csv
import io
from typing import Dict, List, Optional

from .models import StaticRoute, SubnetPlan


def generate_cisco_ios_script(
    plans: List[SubnetPlan],
    static_routes: Optional[Dict[str, List[StaticRoute]]] = None,
) -> str:
    """
    Generates ready-to-paste Cisco IOS CLI configuration scripts for all routers.
    """
    output = []
    output.append("! ==========================================================")
    output.append("! Cisco IOS Router Configuration Script (Generated by pkt-ip-planner)")
    output.append("! Copy and paste each section into the corresponding router CLI")
    output.append("! in Cisco Packet Tracer: CLI tab > enable > configure terminal")
    output.append("! ==========================================================\n")

    # Group router assignments by router name
    router_configs: Dict[str, List[str]] = {}

    for plan in plans:
        for a in plan.assignments:
            if a.device_kind == "Router":
                r_lines = router_configs.setdefault(a.device_name, [])
                r_lines.append(f"interface {a.port_name}")
                r_lines.append(f" description Subnet: {plan.name}")
                r_lines.append(f" ip address {a.ip} {a.netmask}")
                r_lines.append(" no shutdown")
                r_lines.append(" exit")

    for r_name, iface_lines in router_configs.items():
        output.append(f"! ----------------------------------------------------------")
        output.append(f"! Router: {r_name}")
        output.append(f"! ----------------------------------------------------------")
        output.append("enable")
        output.append("configure terminal")
        output.append(f"hostname {r_name}")
        output.append("no ip domain-lookup")
        output.extend(iface_lines)

        # Static routes for this router
        if static_routes and r_name in static_routes and static_routes[r_name]:
            output.append("! Static Routing for Inter-Subnet Communication:")
            for route in static_routes[r_name]:
                output.append(f" {route.ios_command}")

        output.append("exit")
        output.append("write memory")
        output.append("!\n")

    return "\n".join(output)


def generate_address_table_markdown(plans: List[SubnetPlan]) -> str:
    """
    Generates a Markdown address table detailing assignments across all subnets.
    """
    lines = []
    lines.append("| Device Name | Device Type | Interface | Subnet Name | Assigned IP | Subnet Mask | Default Gateway | Role |")
    lines.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")

    for plan in plans:
        for a in plan.assignments:
            lines.append(
                f"| **{a.device_name}** | {a.device_kind} | `{a.port_name}` | {plan.name} | "
                f"`{a.ip}` | `{a.netmask}` | `{a.gateway or 'None'}` | {a.role.capitalize()} |"
            )

    return "\n".join(lines)


def generate_address_table_csv(plans: List[SubnetPlan]) -> str:
    """
    Generates a CSV string representation of the IP address plan.
    """
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow([
        "Device Name",
        "Device Type",
        "Interface",
        "Subnet ID",
        "Subnet Name",
        "Assigned IP",
        "Subnet Mask",
        "Prefix",
        "Default Gateway",
        "Role",
    ])

    for plan in plans:
        for a in plan.assignments:
            writer.writerow([
                a.device_name,
                a.device_kind,
                a.port_name,
                plan.subnet_id,
                plan.name,
                a.ip,
                a.netmask,
                f"/{plan.prefix}",
                a.gateway,
                a.role,
            ])

    return buf.getvalue()


def generate_manual_guide(
    plans: List[SubnetPlan],
    static_routes: Optional[Dict[str, List[StaticRoute]]] = None,
) -> str:
    """
    Generates a step-by-step beginner-friendly guide for manual configuration and testing.
    """
    guide = []
    guide.append("# Beginner's Guide: Configuring and Testing Your Network in Packet Tracer\n")
    guide.append("If you want to verify or manually apply settings, follow these step-by-step instructions:\n")
    
    guide.append("## Step 1: Configure Router Interfaces\n")
    guide.append("1. Click on each Router in Packet Tracer to open its window.")
    guide.append("2. Click on the **CLI** tab.")
    guide.append("3. If asked `Would you like to enter the initial configuration dialog? [yes/no]:`, type `no` and press Enter.")
    guide.append("4. Copy and paste the configuration commands for that router from the generated IOS script.\n")

    guide.append("## Step 2: Configure End Devices (PCs / Laptops / Servers)\n")
    guide.append("1. Click on the device (e.g. `PC1`).")
    guide.append("2. Go to the **Desktop** tab, then click **IP Configuration**.")
    guide.append("3. Select **Static**.")
    guide.append("4. Enter the **IPv4 Address**, **Subnet Mask**, and **Default Gateway** from the Address Table.\n")

    guide.append("## Step 3: Test Network Connectivity Using Ping\n")
    guide.append("1. Click on `PC1` > **Desktop** tab > **Command Prompt**.")
    guide.append("2. Ping its default gateway:")
    guide.append("   `ping <Gateway_IP>` (e.g., `ping 192.168.1.1`) -> Should be 100% successful.")
    guide.append("3. Ping a PC in the remote LAN:")
    guide.append("   `ping <Remote_PC_IP>` (e.g., `ping 192.168.1.130`).\n")

    guide.append("> **Beginner Tip (Why the first ping may timeout):**")
    guide.append("> When you ping across a router for the first time, you may see: `Request timed out.`")
    guide.append("> This is normal! Devices need a moment to resolve MAC addresses using ARP (Address Resolution Protocol),")
    guide.append("> and switches run STP (Spanning Tree Protocol) which takes ~30 seconds after link activation.")
    guide.append("> Simply press the `Fast Forward Time` button (>> in bottom left) or repeat the ping command!")

    return "\n".join(guide)
